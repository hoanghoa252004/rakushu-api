-- 8. SUBTITLE SEGMENTS (1-1 voi transcript_segments, kem speaker)
-- ---------------------------------------------------------------------
INSERT INTO subtitle_segments (id, sequence, subtitle_id, transcript_segment_id, original_text, translated_text, start_time, end_time, speaker_id)
SELECT md5('ss:' || ts.id::text)::uuid,
       ts.sequence, sub.id, ts.id, ts.text, tr.vi, ts.start_time, ts.end_time,
       CASE WHEN ts.sequence <= 2 THEN NULL ELSE tsp.speaker_id END
FROM seed_translation tr
JOIN transcripts t          ON t.video_id = ('52000000-0000-0000-0000-0000000000' || lpad(tr.lesson::text, 2, '0'))::uuid
JOIN transcript_segments ts ON ts.transcript_id = t.id AND ts.sequence = tr.seq
JOIN subtitles sub          ON sub.video_id = t.video_id
LEFT JOIN transcript_speakers tsp ON tsp.id = ts.transcript_speaker_id
ON CONFLICT (transcript_segment_id) DO NOTHING;

