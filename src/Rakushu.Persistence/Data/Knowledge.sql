-- ---------------------------------------------------------------------
-- 4. KNOWLEDGE UNITS / MEANINGS
-- ---------------------------------------------------------------------
CREATE TEMP TABLE seed_unique ON COMMIT DROP AS
SELECT DISTINCT ON (expression) * FROM seed_knowledge ORDER BY expression, ord;

INSERT INTO knowledge_units (id, knowledge_type, knowledge_collection_id, proficiency_level_id, expression, reading, audio_key, source_type, is_active, created_at, updated_at)
SELECT md5('ku:' || s.expression)::uuid,
       CASE s.t WHEN 'V' THEN 'Vocabulary' WHEN 'G' THEN 'Grammar' WHEN 'T' THEN 'Terminology' ELSE 'ProperNoun' END,
       c.id, pl.id, s.expression, COALESCE(NULLIF(s.reading, ''), s.expression), NULL, 'Defined', true, now(), now()
FROM seed_unique s
JOIN knowledge_collections c ON c.code = UPPER(s.col)
JOIN proficiency_levels pl   ON pl.code = s.lvl
ON CONFLICT (id) DO NOTHING;

INSERT INTO knowledge_meanings (id, sort_order, meaning, description, knowledge_unit_id, japanese_meaning)
SELECT md5('km:' || s.expression || ':1')::uuid, 1, left(s.meaning, 100), NULL, md5('ku:' || s.expression)::uuid, ''
FROM seed_unique s
WHERE EXISTS (SELECT 1 FROM knowledge_units u WHERE u.id = md5('ku:' || s.expression)::uuid)
ON CONFLICT (id) DO NOTHING;

INSERT INTO knowledge_meanings (id, sort_order, meaning, description, knowledge_unit_id, japanese_meaning)
SELECT md5('km:' || e.expression || ':' || e.sort_order)::uuid, e.sort_order, left(e.meaning, 100), NULL, md5('ku:' || e.expression)::uuid, ''
FROM seed_meaning_extra e
WHERE EXISTS (SELECT 1 FROM knowledge_units u WHERE u.id = md5('ku:' || e.expression)::uuid)
ON CONFLICT (id) DO NOTHING;

-- ---------------------------------------------------------------------
-- 5. LEARNING UNITS: gan nghia chinh (sort_order = 1) vao tung transcript segment
--    chi khop chuoi co that trong transcript_segments.text (khong khop thi khong tao)
-- ---------------------------------------------------------------------
INSERT INTO learning_units (id, knowledge_meaning_id, transcript_segment_id, start_token_index, end_token_index, confidence, is_reviewed, detection_method)
SELECT md5('lu:' || km.id::text || ':' || ts.id::text)::uuid,
       km.id, ts.id,
       m.pos - 1,
       m.pos - 1 + char_length(ku.expression),
       1.0, true, 'ExactMatch'
FROM seed_unique s
JOIN knowledge_units ku    ON ku.id = md5('ku:' || s.expression)::uuid
JOIN knowledge_meanings km ON km.knowledge_unit_id = ku.id AND km.sort_order = 1
JOIN transcripts t         ON t.video_id BETWEEN '52000000-0000-0000-0000-000000000001'::uuid AND '52000000-0000-0000-0000-000000000015'::uuid
JOIN transcript_segments ts ON ts.transcript_id = t.id
CROSS JOIN LATERAL (SELECT strpos(lower(ts.text), lower(ku.expression)) AS pos) m
WHERE m.pos > 0
ON CONFLICT (id) DO NOTHING;

